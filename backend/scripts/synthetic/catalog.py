from dataclasses import dataclass


@dataclass(frozen=True)
class Trade:
    code: str  # two letters, as in the dataset IDs (TRN-EL-001, PRJ-EL-101)
    name: str
    weight: float  # share of trainees and projects

    @property
    def id(self) -> str:
        # Same convention as ai/tests/dataset.py: the lower-cased, underscored trade name.
        return self.name.lower().replace(" ", "_")


